const root = document.documentElement;
const store = {
  get(k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
  set(k, v) { try { localStorage.setItem(k, v); } catch (e) {} },
};

function applyLang(lang) {
  const dict = i18n[lang] || i18n.en;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const v = dict[el.dataset.i18n];
    if (v) el.textContent = v;
  });
  root.lang = lang;
  document.querySelectorAll(".lang-switch button").forEach((b) => {
    b.classList.toggle("active", b.dataset.lang === lang);
    b.setAttribute("aria-pressed", b.dataset.lang === lang);
  });
}

function setLang(lang) {
  if (lang === root.lang) return;
  store.set("lang", lang);
  const reduce = matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (reduce) return applyLang(lang);
  document.body.classList.add("lang-fading");
  setTimeout(() => {
    applyLang(lang);
    document.body.classList.remove("lang-fading");
  }, 180);
}

applyLang(root.lang === "tr" ? "tr" : "en");
document.querySelectorAll(".lang-switch button").forEach((b) =>
  b.addEventListener("click", () => setLang(b.dataset.lang))
);

// ---------- Theme ----------
document.getElementById("theme-toggle").addEventListener("click", () => {
  const current = root.dataset.theme || (matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");
  const next = current === "dark" ? "light" : "dark";
  root.dataset.theme = next;
  store.set("theme", next);
});

// ---------- Nav border on scroll ----------
const nav = document.querySelector(".nav");
const onScroll = () => nav.classList.toggle("scrolled", window.scrollY > 8);
window.addEventListener("scroll", onScroll, { passive: true });
onScroll();

// ---------- Reveal on scroll (staggered) ----------
const io = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("in");
      io.unobserve(entry.target);
    });
  },
  { threshold: 0.12, rootMargin: "0px 0px -40px 0px" }
);
document.querySelectorAll(".reveal").forEach((el) => {
  const siblings = [...el.parentElement.children].filter((c) => c.classList.contains("reveal"));
  el.style.transitionDelay = `${Math.min(siblings.indexOf(el), 5) * 70}ms`;
  io.observe(el);
});

// Remove stagger delay after reveal so hover transitions stay snappy
document.addEventListener("transitionend", (e) => {
  if (e.target.classList && e.target.classList.contains("in")) e.target.style.transitionDelay = "";
});

document.getElementById("year").textContent = new Date().getFullYear();
